import assert from 'node:assert/strict';
import vm from 'node:vm';
import { readFile } from 'node:fs/promises';
const source = await readFile(new URL('../js/rhine-lab-shortcuts.js',import.meta.url),'utf8');
const storage = new Map();
let failStorage = false;
function load() {
    const context = { window:{dispatchEvent(){}}, CustomEvent:class{}, localStorage:{getItem:key=>storage.get(key),setItem:(key,value)=>{if(failStorage)throw Error('Storage blocked');storage.set(key,value);}} };
    vm.runInNewContext(source,context);
    return context.window.RhineLabShortcuts;
}
let api = load();
assert.equal(api.validate(api.defaults).length,0);
for (const [input,expected] of [[' alt + g ','Alt+G'],['cmd+k','Ctrl+K'],['left','ArrowLeft'],['`','Backquote'],['',''],['Ctrl+Ctrl+A',null],['Alt+',null],['anything',null],[null,null],['a'.repeat(65),null]]) assert.equal(api.normalize(input),expected);
assert.ok(api.validate(null).length);
const key = (key,extra={}) => ({key,...extra});
assert.equal(api.command(key('`')),'mode');
assert.equal(api.command(key('²',{code:'Backquote'})),'mode');
assert.equal(api.display('Backquote'),'`');
assert.equal(api.command(key('g',{code:'KeyG'})),'navigation');
// No modifier chord is a shortcut, including all former Alt bindings and Ctrl+K/Enter.
for (const modifier of ['altKey','ctrlKey','metaKey','shiftKey']) for (const value of ['g','e','k','n','Enter','ArrowUp','`','1']) assert.equal(api.command(key(value,{[modifier]:true})),undefined);
for (const [id,value,code] of [['navigation','E','duplicate'],['search','Ctrl+W','single'],['navigation','Alt+F2','single'],['mode','Enter','reserved'],['mode','Escape','reserved'],['mode','1','reserved'],['mode','F2','reserved'],['create','Ctrl+Q','single'],['create','Ctrl++','invalid'],['edit','ArrowLeft','duplicate']]) {
    const errors = api.validate({...api.defaults,[id]:value});
    assert.ok(errors.some(error=>error.id===id&&error.code===code),JSON.stringify(errors));
    assert.equal(api.save({...api.defaults,[id]:value}).ok,false);
}
const duplicates = api.validate({...api.defaults,navigation:'E'});
assert.ok(duplicates.some(item=>item.id==='edit'&&item.other==='navigation'));
const customized = {...api.defaults,mode:'B',navigation:'H',edit:'T',previousPage:'Q',nextPage:'R'};
assert.equal(api.save(customized).ok,true);
assert.equal(api.command(key('h')),'navigation');
assert.equal(api.command(key('g')),undefined);
assert.equal(api.command(key('t')),'edit');
assert.equal(api.command(key('q')),'previousPage');
assert.equal(api.command(key('ArrowLeft')),'previousPage');
api = load(); assert.equal(api.get('mode'),'B'); assert.equal(api.get('navigation'),'H');
assert.equal(api.save({...customized,navigation:'',previousPage:''}).ok,true);
assert.equal(api.matches(key('h'),'navigation'),false);
assert.equal(api.command(key('ArrowLeft')),undefined);
failStorage = true;
assert.equal(api.save(api.defaults).storage,true);
assert.equal(api.get('navigation'),'');
failStorage = false;
storage.set('rhineLabKeyboardShortcutsV2','not json'); api=load(); assert.equal(api.get('navigation'),'G');
storage.set('rhineLabKeyboardShortcutsV2',JSON.stringify({...api.defaults,navigation:'E'})); api=load(); assert.equal(api.get('navigation'),'G');
storage.delete('rhineLabKeyboardShortcutsV2');
const legacy = {...api.defaults,navigation:'Alt+H',edit:'Alt+B',other:'Alt+A',search:'Ctrl+K',previousAction:'Alt+ArrowUp',nextAction:'Alt+ArrowDown',confirmAction:'Alt+Enter'};
storage.set('rhineLabKeyboardShortcutsV1',JSON.stringify(legacy));
storage.set('rhineLabWorkspace','keep my research');
api=load(); assert.equal(api.get('navigation'),'H'); assert.equal(api.get('edit'),'B'); assert.equal(api.get('other'),'O'); assert.equal(api.get('search'),'K'); assert.equal(api.get('previousAction'),'ArrowUp');
assert.equal(api.get('mode'),'Backquote');
assert.equal(storage.get('rhineLabWorkspace'),'keep my research');
assert.equal(storage.get('rhineLabKeyboardShortcutsV1'),JSON.stringify(legacy));
storage.set('rhineLabKeyboardShortcutsV1',JSON.stringify({...legacy,edit:'Alt+H'}));
api=load();assert.equal(api.get('navigation'),'G','Conflicting migrated keys safely fall back to defaults');
storage.set('rhineLabKeyboardShortcutsV1',JSON.stringify({...legacy,navigation:42}));
api=load();assert.equal(api.get('navigation'),'G','Malformed legacy settings do not break startup');
assert.equal(api.save({...api.defaults,mode:''}).ok,true);assert.equal(api.command(key('`')),undefined);
assert.equal(api.save({...api.defaults,mode:'T'}).ok,true);
api=load(); assert.equal(api.get('mode'),'T'); assert.equal(api.get('navigation'),'G','V2 overrides legacy settings');
console.log('Single-key mode, modifier pass-through, duplicate detection, remapping, aliases, persistence, disable, legacy migration and storage recovery passed.');
